#!/usr/bin/env python3
"""Build references.bib and tools/arxiv_metadata.json from every arXiv ID cited in the repo.

Single source of truth for paper titles: titles are copied verbatim from the arXiv API.
Usage:
    python tools/build_references.py            # refresh metadata from arXiv (network)
    python tools/build_references.py --offline  # rebuild references.bib from the cached JSON only
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
import unicodedata
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
META = ROOT / "tools" / "arxiv_metadata.json"
BIB = ROOT / "references.bib"
SOURCES = ["README.md", "README_zh.md", "labs/README.md", "index.html"] + [
    str(p.relative_to(ROOT)) for p in sorted((ROOT / "docs").glob("*.md"))
]
ID_RE = re.compile(r"arxiv\.org/(?:abs|pdf)/(\d{4}\.\d{4,5})|arXiv:\s?(\d{4}\.\d{4,5})", re.I)
NS = {"a": "http://www.w3.org/2005/Atom", "arxiv": "http://arxiv.org/schemas/atom"}


def collect_ids() -> list[str]:
    ids: set[str] = set()
    for rel in SOURCES:
        text = (ROOT / rel).read_text(encoding="utf-8")
        for m in ID_RE.finditer(text):
            ids.add(m.group(1) or m.group(2))
    return sorted(ids)


def fetch(ids: list[str]) -> dict:
    out: dict = {}
    for k in range(0, len(ids), 50):
        batch = ids[k:k + 50]
        url = "https://export.arxiv.org/api/query?id_list=" + ",".join(batch) + "&max_results=100"
        for attempt in range(4):
            try:
                data = urllib.request.urlopen(url, timeout=90).read()
                break
            except Exception as exc:  # pragma: no cover - network
                print(f"retry {attempt}: {exc}", file=sys.stderr)
                time.sleep(5 * (attempt + 1))
        else:
            raise SystemExit("arXiv API unreachable")
        for e in ET.fromstring(data).findall("a:entry", NS):
            aid = re.sub(r"v\d+$", "", e.find("a:id", NS).text.rsplit("/", 1)[-1])
            title = " ".join((e.find("a:title", NS).text or "").split())
            if not title or title == "Error":
                continue
            out[aid] = {
                "title": title,
                "authors": [" ".join(a.find("a:name", NS).text.split()) for a in e.findall("a:author", NS)],
                "published": (e.find("a:published", NS).text or "")[:10],
                "comment": " ".join((e.findtext("arxiv:comment", default="", namespaces=NS) or "").split()),
                "journal_ref": " ".join((e.findtext("arxiv:journal_ref", default="", namespaces=NS) or "").split()),
            }
        time.sleep(3)
    return out


def bib_key(aid: str, meta: dict) -> str:
    last = meta["authors"][0].split()[-1] if meta["authors"] else "anon"
    last = unicodedata.normalize("NFKD", last).encode("ascii", "ignore").decode().lower()
    last = re.sub(r"[^a-z]", "", last) or "anon"
    word = next((w for w in re.findall(r"[A-Za-z0-9]+", meta["title"]) if len(w) > 3), "paper").lower()
    return f"{last}{meta['published'][:4]}{word}_{aid.replace('.', '_')}"


def render_bib(meta: dict) -> str:
    lines = ["% Auto-generated by tools/build_references.py from the arXiv API. Do not edit by hand.", ""]
    for aid in sorted(meta):
        m = meta[aid]
        title = m["title"]
        authors = " and ".join(m["authors"]) or "Anonymous"
        lines += [
            f"@misc{{{bib_key(aid, m)},",
            f"  title         = {{{{{title}}}}},",
            f"  author        = {{{authors}}},",
            f"  year          = {{{m['published'][:4]}}},",
            f"  eprint        = {{{aid}}},",
            "  archivePrefix = {arXiv},",
            f"  url           = {{https://arxiv.org/abs/{aid}}},",
        ]
        if m.get("journal_ref"):
            lines.append(f"  note          = {{{m['journal_ref']}}},")
        lines += ["}", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--check", action="store_true", help="Check cached titles, dates and generated BibTeX without network or writes")
    args = ap.parse_args()
    ids = collect_ids()
    cached = json.loads(META.read_text(encoding="utf-8")) if META.exists() else {}
    if not args.offline and not args.check:
        cached.update(fetch(ids))
    missing = [i for i in ids if i not in cached]
    meta = {i: cached[i] for i in ids if i in cached}
    if args.check:
        errors = ["Missing metadata: " + i for i in missing]
        for rel in ("README.md", "README_zh.md"):
            checked = 0
            for number, line in enumerate((ROOT / rel).read_text(encoding="utf-8").splitlines(), 1):
                entry = re.search(r'^- \*\*\[(\d{4}\.\d{2})\]\*\* (.*?) \[\[paper\]\(https://arxiv\.org/abs/(\d{4}\.\d{4,5})\)\]', line)
                if not entry or entry[3] not in meta:
                    continue
                checked += 1
                paper = meta[entry[3]]
                raw = re.sub(r'\*\*', '', entry[2]).strip()
                raw_no_venue = re.sub(r'\s*\([^)]*(?:202\d|1000\+)[^)]*\)\s*$', '', raw).strip()
                sub = entry[2].split(": ", 1)[-1].strip()
                sub_no_venue = re.sub(r'\s*\([^)]*(?:202\d|1000\+)[^)]*\)\s*$', '', sub).strip()
                ptitle = paper["title"]
                if ptitle not in (raw, raw_no_venue, sub, sub_no_venue) and not ptitle.endswith(": " + sub_no_venue):
                    errors.append(f"{rel}:{number}: title differs from arXiv metadata ({ptitle})")
                if entry[1] != paper["published"][:7].replace("-", "."):
                    errors.append(f"{rel}:{number}: first-preprint date differs")
            if checked < 85:
                errors.append(f"{rel}: expected >=85 frontier reference lines, matched {checked}")
        if not BIB.exists() or BIB.read_text(encoding="utf-8") != render_bib(meta):
            errors.append("references.bib is stale; run tools/build_references.py --offline")
        if errors:
            raise SystemExit("\n".join(errors))
        print(f"Verified {len(meta)} cached references, portal titles and preprint dates (offline).")
        return
    META.write_text(json.dumps(meta, ensure_ascii=False, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    BIB.write_text(render_bib(meta), encoding="utf-8", newline="\n")
    print(f"{len(meta)} papers written to references.bib; missing from arXiv: {missing}")
    if missing:
        sys.exit(1)


if __name__ == "__main__":
    main()
